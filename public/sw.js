// Service worker mínimo de La Pelu SPA.
// Solo guarda la carcasa de la página (HTML, JS, CSS e imágenes del mismo sitio) para abrir más rápido
// y mostrar la página si no hay señal. NUNCA guarda datos de Firebase, Google ni ningún otro dominio.
// Estrategia: primero la red (siempre la versión más nueva) y, si falla, la copia guardada.
const CACHE = 'la-pelu-shell-v1';

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // Firebase, Google Fonts, etc.: no se tocan

  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.ok && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy)).catch(() => undefined);
        }
        return res;
      })
      .catch(() =>
        caches.match(req).then((hit) => hit || (req.mode === 'navigate' ? caches.match('./index.html') : undefined))
      )
  );
});
